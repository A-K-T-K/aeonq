"""Measure local compiler pipelines on the non-Qiskit SDK targets.

The Qiskit comparison is generated by compiler_comparison.py. SDKs without
normalized gate-depth metrics remain in this output with an explicit reason.
"""

import csv
from datetime import datetime, timezone
from pathlib import Path
from time import perf_counter
import tracemalloc

from aeonq.adapters.cirq import CirqAdapter
from aeonq.adapters.pennylane import PennyLaneAdapter
from aeonq.adapters.qsharp import QSharpAdapter
from aeonq.benchmarks.problems import bernoulli, independent_threshold
from aeonq.compiler import AECompiler
from aeonq.ir import GroverPower, Sequence
from aeonq.ir.registers import RegisterMap
from aeonq.reference import grover_for


def run(
    output: Path, *, powers: tuple[int, ...] = (0, 1, 2, 4, 8, 16, 32)
) -> list[dict]:
    if not powers or any(power < 0 for power in powers):
        raise ValueError("compiler benchmark powers must be nonnegative")
    adapters = {
        "cirq": CirqAdapter(),
        "pennylane": PennyLaneAdapter(),
        "qsharp": QSharpAdapter(),
    }
    compiler = AECompiler()
    rows: list[dict] = []
    for case in (bernoulli(0.25), independent_threshold(2, 2)):
        prep = case.problem.state_preparation
        n = prep.n_qubits
        q = grover_for(case.problem)
        mapping = RegisterMap(tuple(range(n)), tuple(range(n)))
        for power in powers:
            variants = {
                "naive_materialization": Sequence((prep,) + (q,) * power, n),
                "ordinary_sdk": Sequence((prep, GroverPower(q, power, n)), n),
                "ae_aware": Sequence((prep, GroverPower(q, power, n)), n),
            }
            for sdk, adapter in adapters.items():
                for pipeline, ir in variants.items():
                    row = {
                        "timestamp_utc": datetime.now(timezone.utc).isoformat(),
                        "sdk": sdk,
                        "sdk_version": next(
                            iter(adapter.capabilities().metadata.values())
                        ),
                        "case_id": case.case_id,
                        "amplitude": case.a_true,
                        "power": power,
                        "pipeline": pipeline,
                    }
                    tracemalloc.start()
                    started = perf_counter()
                    try:
                        if pipeline == "ae_aware":
                            compiled = compiler.compile(ir, adapter).compiled_program
                        else:
                            compiled = adapter.compile(adapter.lower(ir))
                        row["compile_seconds"] = perf_counter() - started
                        metrics = adapter.resource_metrics(compiled)
                        raw = adapter.execute(compiled, 1, seed=0)
                        if adapter.normalize_result(raw, mapping).shots != 1:
                            raise ValueError("compiled program did not return one shot")
                        row.update(metrics)
                        row["executable_success"] = True
                        row["error"] = ""
                    except Exception as exc:
                        row["compile_seconds"] = perf_counter() - started
                        row["executable_success"] = False
                        row["error"] = f"{type(exc).__name__}: {exc}"
                    finally:
                        _, row["peak_python_bytes"] = tracemalloc.get_traced_memory()
                        tracemalloc.stop()
                    row["ancillas"] = (
                        int(row["qubits"]) - n
                        if row.get("qubits") is not None
                        else None
                    )
                    row["metric_scope"] = (
                        "native operation counts; QDK depth and gate counts unavailable"
                        if sdk == "qsharp"
                        else "native SDK local metrics"
                    )
                    rows.append(row)
    output.parent.mkdir(parents=True, exist_ok=True)
    fields = list(dict.fromkeys(key for row in rows for key in row))
    with output.open("w", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)
    return rows


if __name__ == "__main__":
    run(Path("benchmarks/results/raw/phase12_cross_sdk_compiler.csv"))
